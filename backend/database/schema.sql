-- StudentConnect database schema — hand-written SQL (replaces EF Core migrations).
-- Apply with: psql -U <user> -d studentconnect_db -f schema.sql
-- Idempotent: safe to re-run against an already-provisioned database.

-- Multi-tenancy root — every school using the product is one row here. Grades, Subjects,
-- AcademicYears, Teachers, Students, and Users all carry a SchoolId; Sections/Terms are
-- scoped transitively through their (NOT NULL) GradeId/AcademicYearId foreign keys instead
-- of a redundant column. See docs/solution-architecture-multi-tenancy.md.
CREATE TABLE IF NOT EXISTS "Schools" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" text NOT NULL,
    "Code" text NOT NULL,
    "CreatedAtUtc" timestamp with time zone NOT NULL DEFAULT now(),
    "IsActive" boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Schools_Code" ON "Schools" ("Code");

CREATE TABLE IF NOT EXISTS "Grades" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" text NOT NULL,
    "SchoolId" integer NOT NULL REFERENCES "Schools" ("Id") ON DELETE RESTRICT
);

-- Nullable-then-backfill for installations that already had "Grades" before multi-tenancy —
-- new installs already get it NOT NULL from the CREATE TABLE above. Backfilled in seed.sql.
ALTER TABLE "Grades" ADD COLUMN IF NOT EXISTS "SchoolId" integer REFERENCES "Schools" ("Id");
CREATE INDEX IF NOT EXISTS "IX_Grades_SchoolId" ON "Grades" ("SchoolId");

-- Defined here (before Sections/AcademicYears) since Sections.HomeroomTeacherId references it —
-- a table can't forward-reference one that doesn't exist yet on a genuinely fresh database.
CREATE TABLE IF NOT EXISTS "Teachers" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TeacherId" text NOT NULL,
    "FirstName" text NOT NULL,
    "LastName" text NOT NULL,
    "Email" text NOT NULL,
    "SchoolId" integer NOT NULL REFERENCES "Schools" ("Id") ON DELETE RESTRICT
);
ALTER TABLE "Teachers" ADD COLUMN IF NOT EXISTS "SchoolId" integer REFERENCES "Schools" ("Id");

-- TeacherId (the school-chosen code like "T001") only needs to be unique WITHIN a school —
-- two schools independently choosing the same code is expected, not a conflict.
DROP INDEX IF EXISTS "IX_Teachers_TeacherId";
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Teachers_SchoolId_TeacherId" ON "Teachers" ("SchoolId", "TeacherId");

CREATE TABLE IF NOT EXISTS "AcademicYears" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" text NOT NULL,
    "StartDate" date NOT NULL,
    "EndDate" date NOT NULL,
    "IsCurrent" boolean NOT NULL DEFAULT false,
    "SchoolId" integer NOT NULL REFERENCES "Schools" ("Id") ON DELETE RESTRICT
);

ALTER TABLE "AcademicYears" ADD COLUMN IF NOT EXISTS "SchoolId" integer REFERENCES "Schools" ("Id");
CREATE INDEX IF NOT EXISTS "IX_AcademicYears_SchoolId" ON "AcademicYears" ("SchoolId");

CREATE TABLE IF NOT EXISTS "Terms" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "AcademicYearId" integer NOT NULL REFERENCES "AcademicYears" ("Id") ON DELETE RESTRICT,
    "Name" text NOT NULL,
    "StartDate" date NOT NULL,
    "EndDate" date NOT NULL
);
CREATE INDEX IF NOT EXISTS "IX_Terms_AcademicYearId" ON "Terms" ("AcademicYearId");

-- Replaces the old free-text Student.Section column — a real, admin-manageable entity
-- scoped to a Grade ("Grade 8 - Section A") instead of an arbitrary string per student.
CREATE TABLE IF NOT EXISTS "Sections" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "GradeId" integer NOT NULL REFERENCES "Grades" ("Id") ON DELETE RESTRICT,
    "Name" text NOT NULL,
    "HomeroomTeacherId" integer NULL REFERENCES "Teachers" ("Id") ON DELETE SET NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Sections_GradeId_Name" ON "Sections" ("GradeId", "Name");

-- For an installation that already had "Sections" before homeroom teachers existed.
ALTER TABLE "Sections" ADD COLUMN IF NOT EXISTS "HomeroomTeacherId" integer REFERENCES "Teachers" ("Id") ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS "IX_Sections_HomeroomTeacherId" ON "Sections" ("HomeroomTeacherId");

CREATE TABLE IF NOT EXISTS "Subjects" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" text NOT NULL,
    "Code" text NOT NULL,
    "SchoolId" integer NOT NULL REFERENCES "Schools" ("Id") ON DELETE RESTRICT
);

ALTER TABLE "Subjects" ADD COLUMN IF NOT EXISTS "SchoolId" integer REFERENCES "Schools" ("Id");
CREATE INDEX IF NOT EXISTS "IX_Subjects_SchoolId" ON "Subjects" ("SchoolId");

CREATE TABLE IF NOT EXISTS "Students" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "StudentId" text NOT NULL,
    "FirstName" text NOT NULL,
    "LastName" text NOT NULL,
    "Email" text NOT NULL,
    "GradeId" integer NOT NULL REFERENCES "Grades" ("Id") ON DELETE RESTRICT,
    "SectionId" integer NULL REFERENCES "Sections" ("Id") ON DELETE RESTRICT,
    "SchoolId" integer NOT NULL REFERENCES "Schools" ("Id") ON DELETE RESTRICT
);

-- For an installation that already had "Students" from before Sections existed, the CREATE
-- above is a no-op — add the new column explicitly so existing databases catch up too, BEFORE
-- any index below references it. (The old "Section" text column, if present, is backfilled
-- and dropped in seed.sql, which runs after Sections has been seeded and can resolve text
-- values into Section rows.)
ALTER TABLE "Students" ADD COLUMN IF NOT EXISTS "SectionId" integer REFERENCES "Sections" ("Id");
ALTER TABLE "Students" ADD COLUMN IF NOT EXISTS "SchoolId" integer REFERENCES "Schools" ("Id");

-- StudentId (the school-chosen code like "STU001") only needs to be unique WITHIN a school.
DROP INDEX IF EXISTS "IX_Students_StudentId";
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Students_SchoolId_StudentId" ON "Students" ("SchoolId", "StudentId");
CREATE INDEX IF NOT EXISTS "IX_Students_GradeId" ON "Students" ("GradeId");
CREATE INDEX IF NOT EXISTS "IX_Students_SectionId" ON "Students" ("SectionId");
CREATE INDEX IF NOT EXISTS "IX_Students_SchoolId" ON "Students" ("SchoolId");

CREATE TABLE IF NOT EXISTS "StudentSubjects" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "StudentId" integer NOT NULL REFERENCES "Students" ("Id") ON DELETE RESTRICT,
    "SubjectId" integer NOT NULL REFERENCES "Subjects" ("Id") ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_StudentSubjects_StudentId_SubjectId" ON "StudentSubjects" ("StudentId", "SubjectId");
CREATE INDEX IF NOT EXISTS "IX_StudentSubjects_SubjectId" ON "StudentSubjects" ("SubjectId");

CREATE TABLE IF NOT EXISTS "Attendance" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "StudentId" integer NOT NULL REFERENCES "Students" ("Id") ON DELETE RESTRICT,
    "SubjectId" integer NOT NULL REFERENCES "Subjects" ("Id") ON DELETE RESTRICT,
    "Date" date NOT NULL,
    "Status" text NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Attendance_StudentId_SubjectId_Date" ON "Attendance" ("StudentId", "SubjectId", "Date");
CREATE INDEX IF NOT EXISTS "IX_Attendance_SubjectId" ON "Attendance" ("SubjectId");

CREATE TABLE IF NOT EXISTS "Assessments" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Title" text NOT NULL,
    "SubjectId" integer NOT NULL REFERENCES "Subjects" ("Id") ON DELETE RESTRICT,
    "Date" date NOT NULL,
    "MaximumMarks" integer NOT NULL,
    "AssessmentType" text NOT NULL,
    "Description" text NOT NULL,
    CONSTRAINT "CK_Assessment_MaximumMarks" CHECK ("MaximumMarks" > 0)
);
CREATE INDEX IF NOT EXISTS "IX_Assessments_SubjectId" ON "Assessments" ("SubjectId");

CREATE TABLE IF NOT EXISTS "Marks" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "StudentId" integer NOT NULL REFERENCES "Students" ("Id") ON DELETE RESTRICT,
    "AssessmentId" integer NOT NULL REFERENCES "Assessments" ("Id") ON DELETE RESTRICT,
    "MarksObtained" integer NOT NULL,
    CONSTRAINT "CK_Mark_MarksObtained" CHECK ("MarksObtained" >= 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Marks_StudentId_AssessmentId" ON "Marks" ("StudentId", "AssessmentId");
CREATE INDEX IF NOT EXISTS "IX_Marks_AssessmentId" ON "Marks" ("AssessmentId");

CREATE TABLE IF NOT EXISTS "Homework" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Title" text NOT NULL,
    "Description" text NOT NULL,
    "SubjectId" integer NOT NULL REFERENCES "Subjects" ("Id") ON DELETE RESTRICT,
    "GradeId" integer NOT NULL REFERENCES "Grades" ("Id") ON DELETE RESTRICT,
    "TeacherId" integer NOT NULL REFERENCES "Teachers" ("Id") ON DELETE RESTRICT,
    "CreatedDate" date NOT NULL,
    "DueDate" date NOT NULL
);
CREATE INDEX IF NOT EXISTS "IX_Homework_SubjectId" ON "Homework" ("SubjectId");
CREATE INDEX IF NOT EXISTS "IX_Homework_GradeId" ON "Homework" ("GradeId");
CREATE INDEX IF NOT EXISTS "IX_Homework_TeacherId" ON "Homework" ("TeacherId");

CREATE TABLE IF NOT EXISTS "HomeworkSubmissions" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "HomeworkId" integer NOT NULL REFERENCES "Homework" ("Id") ON DELETE CASCADE,
    "StudentId" integer NOT NULL REFERENCES "Students" ("Id") ON DELETE RESTRICT,
    "SubmittedDate" timestamp with time zone NOT NULL,
    "Status" text NOT NULL,
    "Comments" text NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_HomeworkSubmissions_StudentId_HomeworkId" ON "HomeworkSubmissions" ("StudentId", "HomeworkId");
CREATE INDEX IF NOT EXISTS "IX_HomeworkSubmissions_HomeworkId" ON "HomeworkSubmissions" ("HomeworkId");

CREATE TABLE IF NOT EXISTS "LearningMaterials" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Title" text NOT NULL,
    "Description" text NOT NULL,
    "SubjectId" integer NOT NULL REFERENCES "Subjects" ("Id") ON DELETE RESTRICT,
    "GradeId" integer NOT NULL REFERENCES "Grades" ("Id") ON DELETE RESTRICT,
    "TeacherId" integer NOT NULL REFERENCES "Teachers" ("Id") ON DELETE RESTRICT,
    "FileName" text NOT NULL,
    "StoredFileName" text NOT NULL,
    "ContentType" text NOT NULL,
    "FileSize" bigint NOT NULL,
    "UploadedDate" timestamp with time zone NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_LearningMaterials_StoredFileName" ON "LearningMaterials" ("StoredFileName");
CREATE INDEX IF NOT EXISTS "IX_LearningMaterials_SubjectId" ON "LearningMaterials" ("SubjectId");
CREATE INDEX IF NOT EXISTS "IX_LearningMaterials_GradeId" ON "LearningMaterials" ("GradeId");
CREATE INDEX IF NOT EXISTS "IX_LearningMaterials_TeacherId" ON "LearningMaterials" ("TeacherId");

CREATE TABLE IF NOT EXISTS "Activities" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Title" text NOT NULL,
    "Description" text NOT NULL,
    "Date" timestamp with time zone NOT NULL,
    "Location" text NOT NULL,
    "GradeId" integer NOT NULL REFERENCES "Grades" ("Id") ON DELETE RESTRICT,
    "Capacity" integer NOT NULL,
    "CreatedDate" timestamp with time zone NOT NULL,
    CONSTRAINT "CK_Activity_Capacity" CHECK ("Capacity" > 0)
);
CREATE INDEX IF NOT EXISTS "IX_Activities_GradeId" ON "Activities" ("GradeId");

CREATE TABLE IF NOT EXISTS "ActivityRegistrations" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "StudentId" integer NOT NULL REFERENCES "Students" ("Id") ON DELETE RESTRICT,
    "ActivityId" integer NOT NULL REFERENCES "Activities" ("Id") ON DELETE RESTRICT,
    "RegistrationDate" timestamp with time zone NOT NULL,
    "Status" text NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_ActivityRegistrations_StudentId_ActivityId" ON "ActivityRegistrations" ("StudentId", "ActivityId");
CREATE INDEX IF NOT EXISTS "IX_ActivityRegistrations_ActivityId" ON "ActivityRegistrations" ("ActivityId");

CREATE TABLE IF NOT EXISTS "Users" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Username" text NOT NULL,
    "PasswordHash" text NOT NULL,
    "Role" text NOT NULL,
    "StudentId" integer NULL REFERENCES "Students" ("Id") ON DELETE RESTRICT,
    "TeacherId" integer NULL REFERENCES "Teachers" ("Id") ON DELETE RESTRICT,
    "Email" text NULL,
    "SchoolId" integer NOT NULL REFERENCES "Schools" ("Id") ON DELETE RESTRICT
);
ALTER TABLE "Users" ADD COLUMN IF NOT EXISTS "SchoolId" integer REFERENCES "Schools" ("Id");

-- Username stays GLOBALLY unique (not per-school) — login today takes only a username and
-- password, with no "pick your school" step, so two schools cannot share a username.
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Users_Username" ON "Users" ("Username");
CREATE INDEX IF NOT EXISTS "IX_Users_StudentId" ON "Users" ("StudentId");
CREATE INDEX IF NOT EXISTS "IX_Users_TeacherId" ON "Users" ("TeacherId");
CREATE INDEX IF NOT EXISTS "IX_Users_SchoolId" ON "Users" ("SchoolId");

-- For an installation that already had "Users" before Email existed (Parent accounts have
-- no Student/Teacher row to resolve an email address from, so they need their own column).
ALTER TABLE "Users" ADD COLUMN IF NOT EXISTS "Email" text NULL;

CREATE TABLE IF NOT EXISTS "ParentStudents" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ParentUserId" integer NOT NULL REFERENCES "Users" ("Id") ON DELETE CASCADE,
    "StudentId" integer NOT NULL REFERENCES "Students" ("Id") ON DELETE CASCADE
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_ParentStudents_ParentUserId_StudentId" ON "ParentStudents" ("ParentUserId", "StudentId");
CREATE INDEX IF NOT EXISTS "IX_ParentStudents_StudentId" ON "ParentStudents" ("StudentId");

CREATE TABLE IF NOT EXISTS "Notifications" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId" integer NOT NULL REFERENCES "Users" ("Id") ON DELETE CASCADE,
    "Title" text NOT NULL,
    "Message" text NOT NULL,
    "Type" text NOT NULL,
    "IsRead" boolean NOT NULL,
    "CreatedAtUtc" timestamp with time zone NOT NULL
);
CREATE INDEX IF NOT EXISTS "IX_Notifications_UserId_IsRead" ON "Notifications" ("UserId", "IsRead");

-- Append-only — who/what/when for the mutations that matter most (grade/mark changes,
-- attendance corrections, student record edits, account/permission changes). Never updated
-- or deleted by the app; UserId is nullable so a log entry survives if the user is later removed.
CREATE TABLE IF NOT EXISTS "AuditLogs" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TimestampUtc" timestamp with time zone NOT NULL DEFAULT now(),
    "UserId" integer NULL REFERENCES "Users" ("Id") ON DELETE SET NULL,
    "Username" text NOT NULL,
    "Role" text NOT NULL,
    "Action" text NOT NULL,
    "EntityType" text NOT NULL,
    "EntityId" text NOT NULL,
    "Details" text NULL
);
CREATE INDEX IF NOT EXISTS "IX_AuditLogs_EntityType_EntityId" ON "AuditLogs" ("EntityType", "EntityId");
CREATE INDEX IF NOT EXISTS "IX_AuditLogs_TimestampUtc" ON "AuditLogs" ("TimestampUtc" DESC);

-- Outbox pattern: notification delivery (writing an in-app Notification row) is decoupled
-- from actually sending the email — a row is enqueued here and a background service (see
-- EmailOutboxProcessor) sends it and marks it sent/failed, so a slow or unavailable SMTP
-- server never blocks the HTTP request that triggered the notification.
CREATE TABLE IF NOT EXISTS "EmailOutbox" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ToEmail" text NOT NULL,
    "ToUserId" integer NULL REFERENCES "Users" ("Id") ON DELETE SET NULL,
    "Subject" text NOT NULL,
    "Body" text NOT NULL,
    "CreatedAtUtc" timestamp with time zone NOT NULL DEFAULT now(),
    "SentAtUtc" timestamp with time zone NULL,
    "Attempts" integer NOT NULL DEFAULT 0,
    "LastError" text NULL
);
CREATE INDEX IF NOT EXISTS "IX_EmailOutbox_SentAtUtc" ON "EmailOutbox" ("SentAtUtc");

